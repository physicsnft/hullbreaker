void UI::begin(std::vector<UIVertex>* out, int pxW, int pxH) {
  out_ = out;
  scale_ = (float)pxH / 900.0f;
  H = 900.0f;
  W = (float)pxW / scale_;
}

void UI::quad(float x0, float y0, float x1, float y1, float x2, float y2, float x3, float y3, Color c, uint32_t g0, uint32_t g1) {
  const float s = scale_;
  UIVertex v[4] = {{x0 * s, y0 * s, 0, 0, c.r, c.g, c.b, c.a, g0, g1}, {x1 * s, y1 * s, 1, 0, c.r, c.g, c.b, c.a, g0, g1},
                   {x2 * s, y2 * s, 1, 1, c.r, c.g, c.b, c.a, g0, g1}, {x3 * s, y3 * s, 0, 1, c.r, c.g, c.b, c.a, g0, g1}};
  out_->push_back(v[0]); out_->push_back(v[1]); out_->push_back(v[2]);
  out_->push_back(v[0]); out_->push_back(v[2]); out_->push_back(v[3]);
}

void UI::rect(float x, float y, float w, float h, Color c) { quad(x, y, x + w, y, x + w, y + h, x, y + h, c, 0, 0xFFFFFFFFu); }
void UI::frame(float x, float y, float w, float h, float t, Color c) {
  rect(x, y, w, t, c); rect(x, y + h - t, w, t, c);
  rect(x, y + t, t, h - 2 * t, c); rect(x + w - t, y + t, t, h - 2 * t, c);
}
void UI::line(float x0, float y0, float x1, float y1, float t, Color c) {
  float dx = x1 - x0, dy = y1 - y0, l = std::sqrt(dx * dx + dy * dy);
  if (l < 1e-4f) return;
  float nx = -dy / l * t * 0.5f, ny = dx / l * t * 0.5f;
  quad(x0 + nx, y0 + ny, x1 + nx, y1 + ny, x1 - nx, y1 - ny, x0 - nx, y0 - ny, c, 0, 0xFFFFFFFFu);
}
void UI::disc(float cx, float cy, float r, Color c) { quad(cx - r, cy - r, cx + r, cy - r, cx + r, cy + r, cx - r, cy + r, c, 1, 0xFFFFFFFFu); }
void UI::ring(float cx, float cy, float r, float thick, Color c) {
  uint32_t th = (uint32_t)clampf(thick / r * 255.0f, 1.0f, 255.0f);
  quad(cx - r, cy - r, cx + r, cy - r, cx + r, cy + r, cx - r, cy + r, c, 2u | (th << 8), 0xFFFFFFFFu);
}
void UI::bar(float x, float y, float w, float h, float frac, Color fg, Color bg) {
  rect(x, y, w, h, bg);
  rect(x, y, w * clampf(frac, 0.0f, 1.0f), h, fg);
}
void UI::text(float x, float y, float size, Color c, const std::string& s) {
  float cx = x;
  for (char ch : s) {
    if (ch == '\n') { cx = x; y += 9 * size; continue; }
    if (ch >= 'a' && ch <= 'z') ch = (char)(ch - 32); // the HUD is all caps
    int g = (unsigned char)ch - 32;
    if (g > 0 && g < 95) {
      uint64_t bits = 0;
      for (int col = 0; col < 5; ++col)
        for (int row = 0; row < 7; ++row)
          if (kFont[g][col] & (1 << row)) bits |= 1ull << (col * 7 + row);
      quad(cx, y, cx + 5 * size, y, cx + 5 * size, y + 7 * size, cx, y + 7 * size, c, (uint32_t)bits, (uint32_t)(bits >> 32));
    }
    cx += 6 * size;
  }
}
void UI::textC(float cx, float y, float size, Color c, const std::string& s) { text(cx - textW(s, size) * 0.5f, y, size, c, s); }
void UI::textR(float xr, float y, float size, Color c, const std::string& s) { text(xr - textW(s, size), y, size, c, s); }
float UI::textWrap(float x, float y, float maxW, float size, Color c, const std::string& s) {
  size_t maxChars = (size_t)std::max(8.0f, maxW / (6.0f * size));
  size_t i = 0;
  while (i < s.size()) {
    size_t end = std::min(s.size(), i + maxChars);
    if (end < s.size()) {
      size_t sp = s.rfind(' ', end);
      if (sp != std::string::npos && sp > i) end = sp;
    }
    text(x, y, size, c, s.substr(i, end - i));
    y += 10 * size;
    i = end;
    while (i < s.size() && s[i] == ' ') ++i;
  }
  return y;
}
void UI::brackets(float cx, float cy, float half, float len, float t, Color c) {
  for (int sx = -1; sx <= 1; sx += 2)
    for (int sy = -1; sy <= 1; sy += 2) {
      float x = cx + sx * half, y = cy + sy * half;
      rect(sx < 0 ? x : x - len, sy < 0 ? y : y - t, len, t, c);
      rect(sx < 0 ? x : x - t, sy < 0 ? y : y - len, t, len, c);
    }
}
